"""Priority levels, supporting evidence and the ranked table."""
from __future__ import annotations

from typing import Dict, Optional

import numpy as np
import pandas as pd

from . import config as C
from . import features as F

RANKING_COLUMNS = ["rank", "location_id", "predicted_priority_score", "priority_level",
                   "incident_count", "complaint_count", "unresolved_incident_count",
                   "road_condition", "supporting_evidence",
                   "recent_proxy_score_60d", "injury_count", "open_complaint_count"]


def clip_scores(scores) -> np.ndarray:
    """Displayed scores are clipped to the 0-100 range (regression output is unbounded)."""
    return np.clip(np.asarray(scores, dtype=float), 0.0, 100.0)


def level_thresholds_from_scores(val_scores) -> Dict[str, float]:
    v = clip_scores(val_scores)
    return {lvl: float(np.quantile(v, q)) for lvl, q in C.LEVEL_QUANTILES.items()}


def priority_level(scores, thresholds: Dict[str, float]) -> np.ndarray:
    s = clip_scores(scores)
    out = np.full(s.shape, "Low", dtype=object)
    out[s >= thresholds["Medium"]] = "Medium"
    out[s >= thresholds["High"]] = "High"
    out[s >= thresholds["Critical"]] = "Critical"
    return out


def dominant_incident_types(inc: pd.DataFrame, as_of: pd.Timestamp) -> pd.DataFrame:
    s = inc[inc["timestamp"] <= as_of]
    t = (s.groupby(["location_id", "incident_type"]).size().reset_index(name="n")
          .sort_values(["location_id", "n", "incident_type"], ascending=[True, False, True])
          .drop_duplicates("location_id").set_index("location_id"))
    return t


def _evidence_row(r, as_of_date: str) -> str:
    parts = []
    if r["incident_count"] > 0:
        txt = f"{int(r['incident_count'])} incidents"
        sev = []
        if r["critical_count"]:
            sev.append(f"{int(r['critical_count'])} critical")
        if r["high_count"]:
            sev.append(f"{int(r['high_count'])} high")
        if sev:
            txt += f" ({', '.join(sev)})"
        parts.append(txt)
        if r["injury_count"]:
            parts.append(f"{int(r['injury_count'])} injuries")
        parts.append(f"{int(r['unresolved_incident_count'])} unresolved")
        if isinstance(r.get("top_type"), str):
            parts.append(f"most frequent type: {r['top_type']} ({int(r['top_type_n'])})")
        parts.append(f"last incident {r['last_incident_days_ago']:.0f} days before {as_of_date}")
    else:
        parts.append("no recorded incidents")
    if r["complaint_count"] > 0:
        parts.append(f"{int(r['complaint_count'])} complaints ({int(r['open_complaint_count'])} open)")
    else:
        parts.append("no complaints")
    parts.append(f"road condition {r['road_condition']}")
    if r.get("near_school") == 1:
        parts.append("near a school")
    if r.get("near_hospital") == 1:
        parts.append("near a hospital")
    if r.get("pedestrian_activity") == "High":
        parts.append("high pedestrian activity")
    return "; ".join(parts)


def build_ranking(locations: pd.DataFrame, features: pd.DataFrame, scores,
                  thresholds: Dict[str, float], inc: pd.DataFrame,
                  recent_proxy: Optional[pd.Series], as_of: pd.Timestamp) -> pd.DataFrame:
    """Ranked table for every location in ``features`` (sorted, rank 1 = highest need).

    Evidence is computed from the underlying records (counts and the dominant
    incident type), never generated by the model.
    """
    loc = locations.set_index("location_id")
    df = features[F.RAW_COLUMNS].copy()
    df["predicted_priority_score"] = np.round(clip_scores(scores), 2)
    df["priority_level"] = priority_level(df["predicted_priority_score"], thresholds)
    df["road_condition"] = loc.loc[df.index, "road_condition"].fillna("Unknown")
    df["near_school"] = loc.loc[df.index, "near_school"]
    df["near_hospital"] = loc.loc[df.index, "near_hospital"]
    df["pedestrian_activity"] = loc.loc[df.index, "pedestrian_activity"]
    top = dominant_incident_types(inc, as_of)
    df["top_type"] = top["incident_type"].reindex(df.index)
    df["top_type_n"] = top["n"].reindex(df.index)
    asof_s = str(as_of.date())
    df["supporting_evidence"] = df.apply(lambda r: _evidence_row(r, asof_s), axis=1)
    df["recent_proxy_score_60d"] = (np.round(recent_proxy.reindex(df.index), 2)
                                    if recent_proxy is not None else np.nan)
    df = df.reset_index().sort_values(["predicted_priority_score", "incident_count", "location_id"],
                                      ascending=[False, False, True]).reset_index(drop=True)
    df.insert(0, "rank", np.arange(1, len(df) + 1))
    return df[RANKING_COLUMNS]
